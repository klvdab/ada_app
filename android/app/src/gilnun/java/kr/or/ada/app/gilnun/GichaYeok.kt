    /** 가장 가까운 기차역과 거리(미터) — 반경 안에 없으면 null */
    fun gakkaun(lat: Double, lon: Double, banGyeong: Double = 400.0): Pair<String, Double>? {
        var choe: Pair<String, Double>? = null
        for (y in mokrok) {
            val d = geoRi(lat, lon, y.lat, y.lon)
            if (d <= banGyeong && d < (choe?.second ?: Double.MAX_VALUE)) choe = y.ireum to d
        }
        return choe
    }

    /** 이번 탈것이 기차인가 — 기차역 근처에서 탔고, 목적지가 다른 기차역 1.5킬로미터 안이거나 이름이 「○○역」, 곧은 거리 25킬로미터 넘게 멂 */
    fun gichaInga(lat: Double, lon: Double, mokIreum: String?, mokLat: Double?, mokLon: Double?): String? {
        val t = gakkaun(lat, lon) ?: return null
        if (mokLat == null || mokLon == null) return null
        if (geoRi(lat, lon, mokLat, mokLon) < 25_000) return null
        val mokYeok = gakkaun(mokLat, mokLon, 1500.0)
        val ireumYeok = mokIreum != null && mokrok.any { mokIreum.startsWith(it.ireum + "역") }
        if (!((mokYeok != null && mokYeok.first != t.first) || ireumYeok)) return null
        return t.first
    }

    private fun geoRi(a1: Double, o1: Double, a2: Double, o2: Double): Double {
        val r = 6371000.0
        val p1 = Math.toRadians(a1); val p2 = Math.toRadians(a2)
        val dp = Math.toRadians(a2 - a1); val dl = Math.toRadians(o2 - o1)
        val h = Math.sin(dp / 2) * Math.sin(dp / 2) + Math.cos(p1) * Math.cos(p2) * Math.sin(dl / 2) * Math.sin(dl / 2)
        return 2 * r * Math.asin(Math.sqrt(h))
    }
