    /** 길눈에 없는 기능을 청하는 말이면 그 대답, 아니면 null */
    fun dap(z: String): String? {
        val zl = z.lowercase()
        for (g in MOK) {
            if (g.itda.none { zl.contains(it) }) continue
            if (g.anida.any { zl.contains(it) }) continue
            val josa = IljeongMal.eun(g.ireum)
            return "죄송합니다. ${g.ireum}$josa 아직 길눈에 없는 기능입니다." + (if (g.deotmal.isNotEmpty()) " " + g.deotmal else "") +
                " 이 말씀은 기록해 두었다가 다음에 넣을 때 참고하겠습니다."
        }
        return null
    }

