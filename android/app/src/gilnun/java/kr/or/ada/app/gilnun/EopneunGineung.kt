        if (!(z.contains("택시") || z.contains("우버"))) return false
        if (listOf("취소", "콜", "교통약자", "장애인", "바우처", "왔", "탔", "기다려", "기사", "타는곳", "승강장", "정류장", "필요없", "필요는없", "했어", "했다", "했는데").any { z.contains(it) }) return false
        return listOf("불러", "부를", "부르", "잡아", "잡을", "예약", "필요", "찾아", "준비", "호출", "보내줘", "오게", "와줘", "부탁").any { z.contains(it) }
    }

    /** 이용 기록에 남길 갈래 이름 */
    fun galrae(z: String): String? {
        val zl = z.lowercase()
        return MOK.firstOrNull { g -> g.itda.any { zl.contains(it) } && g.anida.none { zl.contains(it) } }?.ireum
    }
