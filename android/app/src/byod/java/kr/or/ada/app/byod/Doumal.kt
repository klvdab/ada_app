    fun chatgi(mal: String): List<Hang> {
        val nat = mal.trim().split(Regex("\\s+")).filter { it.isNotEmpty() }
        if (nat.isEmpty()) return modu
        return modu.filter { h -> nat.all { h.jemok.contains(it) || h.naeyong.contains(it) } }
    }
