    /// 가장 가까운 기차역과 거리(미터) — 반경 안에 없으면 nil
    static func gakkaun(_ lat: Double, _ lon: Double, banGyeong: Double = 400) -> (ireum: String, geori: Double)? {
        var choe: (String, Double)?
        for (n, la, lo) in mokrok {
            let d = WichiEngine.geori(lat, lon, la, lo)
            if d <= banGyeong && d < (choe?.1 ?? .infinity) { choe = (n, d) }
        }
        return choe.map { ($0.0, $0.1) }
    }

    /// 이번 탈것이 기차인가 — 기차역 근처에서 탔고, 목적지가 다른 기차역 1.5킬로미터 안이거나
    ///   목적지 이름이 「○○역」으로 기차역 이름과 같으며, 곧은 거리 25킬로미터 넘게 멂
    static func gichaInga(tan lat: Double, _ lon: Double, mok: Mokjeok?) -> String? {
        guard let t = gakkaun(lat, lon), let m = mok else { return nil }
        guard WichiEngine.geori(lat, lon, m.lat, m.lon) >= 25_000 else { return nil }
        let mokYeok = gakkaun(m.lat, m.lon, banGyeong: 1500)
        let ireumYeok = mokrok.contains { m.ireum.hasPrefix($0.0 + "역") }
        guard (mokYeok != nil && mokYeok?.ireum != t.ireum) || ireumYeok else { return nil }
        return t.ireum
    }
